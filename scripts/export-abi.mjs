// Copies contract ABIs and deployment addresses from Foundry output into packages/contracts.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const target = join(root, "packages", "contracts", "src", "generated");
mkdirSync(target, { recursive: true });

const contracts = [
  "AssetToken",
  "AssetCompliance",
  "AssetRegistry",
  "AssetFactory",
  "IdentityRegistry",
  "IssuanceDesk",
  "MockUSDC",
];

const camel = (name) => name[0].toLowerCase() + name.slice(1);
let abis = "// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.\n\n";
for (const name of contracts) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run "pnpm contracts:build" first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  abis += `export const ${camel(name)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(target, "abis.ts"), abis);

const deploymentsDir = join(root, "contracts", "deployments");
const deployments = {};
for (const file of existsSync(deploymentsDir) ? readdirSync(deploymentsDir) : []) {
  if (!file.endsWith(".json")) continue;
  const data = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
  deployments[data.chainId] = data;
}
writeFileSync(
  join(target, "deployments.ts"),
  "// Generated by scripts/export-abi.mjs from contracts/deployments. Do not edit.\n\n" +
    `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log(`ABIs for ${contracts.length} contracts and ${Object.keys(deployments).length} deployment(s) exported.`);
